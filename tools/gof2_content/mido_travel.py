def extract_mido_travel(mach, arrival, station, training, population=None, resources=None):
    if station.get('scope') != 'first_station_entry' or training.get('scope') != 'combat_training_encounter_construction':
        return {}
    if getattr(mach, 'architecture', None) == 'android-armv7':
        # Requires the arrival staging, as the Mac anchors on its actor.
        staged = isinstance(arrival, dict) and arrival.get('scope') == 'rescue_choreography' and 'actor' in arrival.get('provenance', {})
        variant, proof = 2, recognize_symbols(mach, ANDROID) if staged else {}
        prove = lambda layout: recognize_symbols(mach, layout)
    else:
        variant, proof = hashed_variants(mach, arrival, [
            {**LAYOUTS, **CONTINUATION_LAYOUTS, **RETURN_LAYOUTS},
            {**MAC_ALTERNATE, **MAC_CONTINUATION_LAYOUTS, **MAC_RETURN_LAYOUTS}])
        prove = lambda layout: hashed_declarations(mach, arrival, layout)
    if not proof:
        return {}
    result = copy.deepcopy((VALUES, MAC_VALUES, ANDROID_VALUES)[variant])
    result['provenance'] = proof
    result['continuation'] = copy.deepcopy((CONTINUATION, MAC_CONTINUATION, MAC_CONTINUATION)[variant])
    result['return_visit'] = copy.deepcopy((RETURN_VISIT, MAC_RETURN_VISIT, ANDROID_RETURN_VISIT)[variant])
    entry_proof = prove((ARRIVAL_BRIEFING_LAYOUTS, MAC_ARRIVAL_BRIEFING_LAYOUTS, ANDROID_ARRIVAL_BRIEFING)[variant])
    if entry_proof:
        result['arrival_briefing'] = copy.deepcopy((ARRIVAL_BRIEFING, MAC_ARRIVAL_BRIEFING, MAC_ARRIVAL_BRIEFING)[variant])
        proof.update(entry_proof)
    navigation_proof = prove((NAVIGATION_LAYOUTS, MAC_NAVIGATION_LAYOUTS, ANDROID_NAVIGATION)[variant])
    if navigation_proof:
        result['contract_navigation'] = copy.deepcopy(CONTRACT_NAVIGATION)
        result['provenance'].update(navigation_proof)
        # Each extension depends on its preceding supported capability. Stop
        # at the first missing proof, preserving earlier standalone readers.
        extensions = (
            ('contract_completion', extract_lounge_story),
            ('convoy_capture', extract_convoy_capture),
            ('convoy_ship', extract_convoy_ship),
            ('convoy_lifecycle', extract_convoy_lifecycle),
            ('convoy_effects', extract_convoy_effects),
            ('alioth_arrival', extract_alioth_arrival),
            ('convoy_transit', extract_convoy_transit),
            ('alioth_attack', extract_alioth_attack),
            ('alioth_lifecycle', extract_alioth_lifecycle),
            ('alioth_flight', extract_alioth_flight),
            ('alioth_return', extract_alioth_return),
            ('free_navigation', extract_free_navigation),
            ('free_population', extract_free_population),
            ('free_traffic', extract_free_traffic),
            ('free_lifecycle', extract_free_lifecycle),
            ('free_flight', extract_free_flight),
            ('free_arrival', extract_free_arrival),
            ('gate_environment', extract_gate_environment),
            ('local_arrival_environment', extract_local_arrival_environment),
            ('gate_transit', extract_gate_transit),
            ('ordinary_worlds', extract_ordinary_worlds),
            ('gate_arrival', extract_gate_arrival),
            ('ordinary_shopping', extract_ordinary_shopping),
            ('ordinary_fitting', extract_ordinary_fitting),
            ('ordinary_contracts', extract_ordinary_contracts),
            ('suttnar_visit', extract_suttnar_visit),
            ('kappa_preparation', extract_kappa_preparation),
            ('emp_bombs', extract_emp_bombs),
            ('kappa_rescue', extract_kappa_rescue),
            ('kappa_fighters', extract_kappa_fighters),
            ('kappa_lifecycle', extract_kappa_lifecycle),
            ('secondary_ownership', extract_secondary_ownership),
            ('kappa_return', extract_kappa_return),
            ('kappa_outcome', extract_kappa_outcome),
            ('kappa_departure', extract_kappa_departure),
            ('sahi_visit', extract_sahi_visit),
            ('sahi_encounter', extract_sahi_encounter),
            ('sahi_stage', extract_sahi_stage),
            ('tractor_recovery', extract_tractor_recovery),
            ('void_portal', extract_void_portal),
            ('post_sahi', extract_post_sahi),
            ('thynome_expedition', extract_thynome_expedition),
            ('void_probe', extract_void_probe),
            ('dima_return', extract_dima_return),
            ('post_probe_visits', extract_post_probe_visits),
            ('void_access', lambda m, a: extract_void_access(m, a, result['post_probe_visits'])),
            ('void_crystals', lambda m, a: extract_void_crystals(m, a, result['post_probe_visits'], population, resources)),
            ('nehma_visit', lambda m, a: extract_nehma_visit(m, a, result['void_crystals'])),
            ('gakkrr_visit', lambda m, a: extract_gakkrr_visit(m, a, result['nehma_visit'])),
            ('bakka_contest', lambda m, a: extract_bakka_contest(m, a, result['gakkrr_visit'])),
            ('bakka_return', lambda m, a: extract_bakka_return(m, a, result['bakka_contest'])),
            ('dekato_convoy', lambda m, a: extract_dekato_convoy(m, a, result['bakka_return'])),
            ('nehma_return', lambda m, a: extract_nehma_return(m, a, result['dekato_convoy'])),
        )
        for name, extract in extensions:
            values, evidence = extract(mach, arrival)
            if not values:
                break
            result[name] = values
            result['provenance'].update(evidence)
    # Ship support is independent of later campaign extensions.
    if 'free_lifecycle' in result:
        from .vossk_traffic import extract_vossk_traffic
        values, evidence = extract_vossk_traffic(mach, arrival)
        if values:
            result['vossk_traffic'] = values
            result['provenance'].update(evidence)
            from .vossk_lod import extract_vossk_lod
            values, evidence = extract_vossk_lod(mach, arrival)
            if values:
                result['vossk_lod'] = values
                result['provenance'].update(evidence)
    return result

